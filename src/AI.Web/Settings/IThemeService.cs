namespace AI.Web.Settings;

using AI.Contracts.Themes;

public interface IThemeService
{
    ValueTask<ThemePreference> GetAsync();

    /// <summary>Saves the preference and repaints the page with it right away.</summary>
    ValueTask SetAsync(ThemePreference preference);

    /// <summary>The accent on the page: the active saved theme's own, or the one the presets share.</summary>
    ValueTask<AccentColor> GetAccentAsync();

    /// <summary>The accent the presets share, whichever theme paints the page now.</summary>
    ValueTask<AccentColor> GetPresetAccentAsync();

    /// <summary>
    /// Saves the accent as the active saved theme's own, or as the presets' one while a preset paints
    /// the page, and recolours the page with it right away.
    /// </summary>
    ValueTask SetAccentAsync(AccentColor accent);

    ValueTask<int> GetCornerRoundnessAsync();

    /// <summary>Saves the corner roundness and updates the page right away.</summary>
    ValueTask SetCornerRoundnessAsync(int percent);

    /// <summary>The themes this client saved, in the order they were added.</summary>
    ValueTask<IReadOnlyList<CustomTheme>> GetCustomThemesAsync();

    /// <summary>The theme the page paints with, or null while a preset is in use.</summary>
    ValueTask<CustomTheme?> GetActiveCustomThemeAsync();

    /// <summary>
    /// Saves <paramref name="seeds"/> under <paramref name="id"/>, or as a new theme when the id is
    /// empty or not saved here, and makes it the active theme. Its palette is generated by
    /// <see cref="ThemePalette"/>, so a theme never stores colours the engine did not produce.
    /// </summary>
    ValueTask<CustomTheme> SaveCustomThemeAsync(string? id, string name, CustomThemeSeeds seeds);

    /// <summary>Paints the page with a saved theme, or returns to the preset preference when null.</summary>
    ValueTask SetActiveCustomThemeAsync(string? id);

    /// <summary>
    /// Paints the page with a theme that is not saved yet, so the studio shows each choice as it is made.
    /// Nothing is written: a reload, or picking a preset, puts the saved theme back. A null theme removes
    /// the palette, which is what closing the studio does with a choice the person did not keep.
    /// </summary>
    ValueTask PreviewCustomThemeAsync(CustomTheme? theme);

    /// <summary>
    /// Removes a saved theme. Removing the active one returns the page to its preset preference rather
    /// than leaving it painted with a palette that no longer exists.
    /// </summary>
    ValueTask DeleteCustomThemeAsync(string id);
}
