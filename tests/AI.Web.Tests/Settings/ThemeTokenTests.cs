namespace AI.Web.Tests.Settings;

using AI.Contracts.Themes;
using Shouldly;
using Xunit;

/// <summary>
/// The registry is the contract between the stylesheet, the engine and the studio: a role that is in
/// neither list can never be painted, and a role in both would be painted twice. These tests read
/// app.css itself, so a token added there without a decision here fails the build instead of silently
/// vanishing under a user theme.
/// </summary>
public sealed class ThemeTokenTests
{
    private static readonly string[] CssColorTokens = ReadCssColorTokens();

    [Fact]
    public void ShouldCoverEveryColourTokenOfTheStylesheetExactlyOnce()
    {
        var registered = ThemeToken.All
            .Concat(ThemeToken.Reserved.Keys)
            .Concat(ThemeToken.ReservedContextLayers)
            .ToArray();

        CssColorTokens.Except(registered).ShouldBeEmpty(
            "every --color-* token of app.css must be either generated by a theme or reserved with a reason");
        registered.Except(CssColorTokens).ShouldBeEmpty(
            "the registry must not name a token app.css does not define");
        registered.Distinct(StringComparer.Ordinal).Count().ShouldBe(registered.Length);
    }

    [Fact]
    public void ShouldNotBothGenerateAndReserveARole()
    {
        ThemeToken.All.Intersect(ThemeToken.Reserved.Keys, StringComparer.Ordinal).ShouldBeEmpty();
        ThemeToken.All.Intersect(ThemeToken.ReservedContextLayers, StringComparer.Ordinal).ShouldBeEmpty();
        ThemeToken.Reserved.Keys.Intersect(ThemeToken.ReservedContextLayers, StringComparer.Ordinal).ShouldBeEmpty();
    }

    [Fact]
    public void ShouldKeepSemanticRolesOutOfThemesAndGiveEachAReason()
    {
        foreach (var role in new[] { "unread", "brand", "generating", "user-bubble", "highlight-bg", "accent-strong" })
        {
            ThemeToken.IsReserved(role).ShouldBeTrue($"{role} says what a mark means, so a theme must not repaint it");
            ThemeToken.IsThemable(role).ShouldBeFalse();
        }

        ThemeToken.Reserved.Values.ShouldAllBe(reason => !string.IsNullOrWhiteSpace(reason));
    }

    [Fact]
    public void ShouldGenerateTheStatusRolesThatAPersonMayTint()
    {
        foreach (var role in new[] { ThemeToken.Danger, ThemeToken.DangerText, ThemeToken.Warning, ThemeToken.SuccessText })
            ThemeToken.IsThemable(role).ShouldBeTrue();
    }

    private static string[] ReadCssColorTokens()
    {
        // The dark base block is the complete palette; every other theme block overrides parts of it.
        var stylesheet = File.ReadAllText(Path.Combine(RepositoryRoot(), "src", "AI.Web", "wwwroot", "css", "app.css"))
            .Replace("\r\n", "\n");
        var start = stylesheet.IndexOf(":root,\n:root[data-theme=\"dark\"] {", StringComparison.Ordinal);
        start.ShouldBeGreaterThan(-1, "the dark base block of app.css was not found");
        var end = stylesheet.IndexOf("\n}\n", start, StringComparison.Ordinal);
        end.ShouldBeGreaterThan(start);
        return
        [
            .. System.Text.RegularExpressions.Regex
                .Matches(stylesheet[start..end], @"^\s*--color-([a-z0-9-]+)\s*:", System.Text.RegularExpressions.RegexOptions.Multiline)
                .Select(match => match.Groups[1].Value)
                .Distinct(StringComparer.Ordinal)
        ];
    }

    /// <summary>The test binary runs from tests/AI.Web.Tests/bin/…, so the repository is four levels up.</summary>
    private static string RepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "AI.slnx")))
            directory = directory.Parent;
        directory.ShouldNotBeNull("the repository root with AI.slnx was not found above the test binary");
        return directory.FullName;
    }
}
